-- Initializes the default user structure:
--   Personal account
--   Cash wallet
--   Whish wallet
--   Default categories
--   User preferences
--
-- Call after creating a new user:
--   CALL sp_initialize_user(<user_id>);

CREATE PROCEDURE sp_initialize_user(IN p_user_id BIGINT UNSIGNED)
BEGIN
    DECLARE v_currency CHAR(3);
    DECLARE v_account_id BIGINT UNSIGNED;
    DECLARE v_cash_wallet_id BIGINT UNSIGNED;

    SELECT preferred_currency
    INTO v_currency
    FROM users
    WHERE id = p_user_id
      AND deleted_at IS NULL
    LIMIT 1;

    IF v_currency IS NULL THEN
        SIGNAL SQLSTATE '45000'
        SET MESSAGE_TEXT = 'User not found';
    END IF;

    INSERT INTO accounts (
        public_id,
        user_id,
        parent_account_id,
        name,
        description,
        sort_order,
        is_active
    )
    VALUES (
        UUID(),
        p_user_id,
        NULL,
        'Personal',
        'Default personal account',
        10,
        1
    );

    SET v_account_id = LAST_INSERT_ID();

    INSERT INTO wallets (
        public_id,
        user_id,
        account_id,
        wallet_type_code,
        name,
        currency_code,
        opening_balance,
        sort_order,
        is_active
    )
    VALUES
    (
        UUID(),
        p_user_id,
        v_account_id,
        'CASH',
        'Cash',
        v_currency,
        0.00,
        10,
        1
    );

    SET v_cash_wallet_id = LAST_INSERT_ID();

    INSERT INTO wallets (
        public_id,
        user_id,
        account_id,
        wallet_type_code,
        name,
        currency_code,
        opening_balance,
        sort_order,
        is_active
    )
    VALUES
    (
        UUID(),
        p_user_id,
        v_account_id,
        'WHISH',
        'Whish',
        v_currency,
        0.00,
        20,
        1
    );

    INSERT INTO categories (
        public_id,
        user_id,
        name,
        applies_to,
        sort_order,
        is_active
    )
    SELECT
        UUID(),
        p_user_id,
        dc.name,
        dc.applies_to,
        dc.sort_order,
        1
    FROM default_categories dc
    WHERE dc.is_active = 1;

    INSERT INTO user_preferences (
        user_id,
        default_account_id,
        default_wallet_id,
        financial_month_start,
        allow_negative_wallets
    )
    VALUES (
        p_user_id,
        v_account_id,
        v_cash_wallet_id,
        1,
        0
    );
END$$

-- Creates monthly pending occurrences for every active static expense.
-- If due_day is 29/30/31 and the selected month is shorter, the occurrence
-- falls on the month's final day.
--
-- Safe to call repeatedly because the unique key prevents duplicates.
--
-- Example:
--   CALL sp_generate_static_expenses_for_month(1, 2026, 9);

CREATE PROCEDURE sp_generate_static_expenses_for_month(
    IN p_user_id BIGINT UNSIGNED,
    IN p_year SMALLINT UNSIGNED,
    IN p_month TINYINT UNSIGNED
)
BEGIN
    DECLARE v_first_day DATE;
    DECLARE v_last_day DATE;

    IF p_month < 1 OR p_month > 12 THEN
        SIGNAL SQLSTATE '45000'
        SET MESSAGE_TEXT = 'Month must be between 1 and 12';
    END IF;

    SET v_first_day =
        STR_TO_DATE(
            CONCAT(p_year, '-', LPAD(p_month, 2, '0'), '-01'),
            '%Y-%m-%d'
        );

    SET v_last_day = LAST_DAY(v_first_day);

    INSERT IGNORE INTO static_expense_occurrences (
        public_id,
        user_id,
        template_id,
        due_year,
        due_month,
        due_date,
        expected_amount,
        status
    )
    SELECT
        UUID(),
        s.user_id,
        s.id,
        p_year,
        p_month,
        DATE_ADD(
            v_first_day,
            INTERVAL (
                LEAST(s.due_day, DAY(v_last_day)) - 1
            ) DAY
        ),
        s.default_amount,
        'PENDING'
    FROM static_expense_templates s
    WHERE s.user_id = p_user_id
      AND s.is_active = 1
      AND s.start_date <= v_last_day
      AND (s.end_date IS NULL OR s.end_date >= v_first_day);
END$$

