DELIMITER $$

-- Users ---------------------------------------------------------------

CREATE TRIGGER trg_users_bi
BEFORE INSERT ON users
FOR EACH ROW
BEGIN
    IF NEW.public_id IS NULL OR NEW.public_id = '' THEN
        SET NEW.public_id = UUID();
    END IF;

    SET NEW.email = LOWER(TRIM(NEW.email));
    SET NEW.preferred_currency = UPPER(TRIM(NEW.preferred_currency));
END$$

CREATE TRIGGER trg_users_bu
BEFORE UPDATE ON users
FOR EACH ROW
BEGIN
    SET NEW.email = LOWER(TRIM(NEW.email));
    SET NEW.preferred_currency = UPPER(TRIM(NEW.preferred_currency));
END$$

-- Accounts ------------------------------------------------------------

CREATE TRIGGER trg_accounts_bi
BEFORE INSERT ON accounts
FOR EACH ROW
BEGIN
    DECLARE v_parent_user BIGINT UNSIGNED;

    IF NEW.public_id IS NULL OR NEW.public_id = '' THEN
        SET NEW.public_id = UUID();
    END IF;

    IF NEW.parent_account_id IS NOT NULL THEN
        SELECT user_id INTO v_parent_user
        FROM accounts
        WHERE id = NEW.parent_account_id
        LIMIT 1;

        IF v_parent_user IS NULL OR v_parent_user <> NEW.user_id THEN
            SIGNAL SQLSTATE '45000'
            SET MESSAGE_TEXT = 'Parent account must belong to the same user';
        END IF;
    END IF;
END$$

CREATE TRIGGER trg_accounts_bu
BEFORE UPDATE ON accounts
FOR EACH ROW
BEGIN
    DECLARE v_parent_user BIGINT UNSIGNED;

    IF NEW.parent_account_id = NEW.id THEN
        SIGNAL SQLSTATE '45000'
        SET MESSAGE_TEXT = 'An account cannot be its own parent';
    END IF;

    IF NEW.parent_account_id IS NOT NULL THEN
        SELECT user_id INTO v_parent_user
        FROM accounts
        WHERE id = NEW.parent_account_id
        LIMIT 1;

        IF v_parent_user IS NULL OR v_parent_user <> NEW.user_id THEN
            SIGNAL SQLSTATE '45000'
            SET MESSAGE_TEXT = 'Parent account must belong to the same user';
        END IF;
    END IF;
END$$

