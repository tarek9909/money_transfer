-- Wallet balance:
-- opening balance
-- + main/additional income
-- - static/dynamic spending
-- + completed transfers in
-- - completed transfers out

CREATE VIEW v_wallet_balances AS
SELECT
    w.id AS wallet_id,
    w.public_id AS wallet_public_id,
    w.user_id,
    w.account_id,
    w.name AS wallet_name,
    w.wallet_type_code,
    w.currency_code,
    w.opening_balance,

    COALESCE((
        SELECT SUM(
            CASE
                WHEN t.transaction_type IN ('MAIN_INCOME','ADDITIONAL_INCOME')
                    THEN t.amount
                WHEN t.transaction_type IN ('STATIC_SPENDING','DYNAMIC_SPENDING')
                    THEN -t.amount
                ELSE 0
            END
        )
        FROM transactions t
        WHERE t.wallet_id = w.id
          AND t.status = 'POSTED'
          AND t.deleted_at IS NULL
    ), 0.00) AS transaction_net,

    COALESCE((
        SELECT SUM(tr.amount)
        FROM transfers tr
        WHERE tr.to_wallet_id = w.id
          AND tr.status = 'COMPLETED'
          AND tr.deleted_at IS NULL
    ), 0.00) AS transfers_in,

    COALESCE((
        SELECT SUM(tr.amount)
        FROM transfers tr
        WHERE tr.from_wallet_id = w.id
          AND tr.status = 'COMPLETED'
          AND tr.deleted_at IS NULL
    ), 0.00) AS transfers_out,

    (
        w.opening_balance
        + COALESCE((
            SELECT SUM(
                CASE
                    WHEN t.transaction_type IN ('MAIN_INCOME','ADDITIONAL_INCOME')
                        THEN t.amount
                    WHEN t.transaction_type IN ('STATIC_SPENDING','DYNAMIC_SPENDING')
                        THEN -t.amount
                    ELSE 0
                END
            )
            FROM transactions t
            WHERE t.wallet_id = w.id
              AND t.status = 'POSTED'
              AND t.deleted_at IS NULL
        ), 0.00)
        + COALESCE((
            SELECT SUM(tr.amount)
            FROM transfers tr
            WHERE tr.to_wallet_id = w.id
              AND tr.status = 'COMPLETED'
              AND tr.deleted_at IS NULL
        ), 0.00)
        - COALESCE((
            SELECT SUM(tr.amount)
            FROM transfers tr
            WHERE tr.from_wallet_id = w.id
              AND tr.status = 'COMPLETED'
              AND tr.deleted_at IS NULL
        ), 0.00)
    ) AS current_balance

FROM wallets w;

-- Direct wallet totals per account. Parent/sub-account rollups should be
-- calculated in Node.js when descendant accounts are included.

CREATE VIEW v_account_balances AS
SELECT
    a.id AS account_id,
    a.public_id AS account_public_id,
    a.user_id,
    a.parent_account_id,
    a.name AS account_name,
    wb.currency_code,
    SUM(wb.current_balance) AS current_balance
FROM accounts a
JOIN v_wallet_balances wb
  ON wb.account_id = a.id
WHERE a.is_active = 1
GROUP BY
    a.id,
    a.public_id,
    a.user_id,
    a.parent_account_id,
    a.name,
    wb.currency_code;

CREATE VIEW v_user_balances_by_currency AS
SELECT
    user_id,
    currency_code,
    SUM(current_balance) AS total_balance
FROM v_wallet_balances
GROUP BY user_id, currency_code;

CREATE VIEW v_monthly_financial_summary AS
SELECT
    t.user_id,
    YEAR(t.transaction_date) AS summary_year,
    MONTH(t.transaction_date) AS summary_month,
    t.currency_code,

    SUM(
        CASE WHEN t.transaction_type = 'MAIN_INCOME'
             THEN t.amount ELSE 0 END
    ) AS main_income,

    SUM(
        CASE WHEN t.transaction_type = 'ADDITIONAL_INCOME'
             THEN t.amount ELSE 0 END
    ) AS additional_income,

    SUM(
        CASE WHEN t.transaction_type IN ('MAIN_INCOME','ADDITIONAL_INCOME')
             THEN t.amount ELSE 0 END
    ) AS total_income,

    SUM(
        CASE WHEN t.transaction_type = 'STATIC_SPENDING'
             THEN t.amount ELSE 0 END
    ) AS static_spending,

    SUM(
        CASE WHEN t.transaction_type = 'DYNAMIC_SPENDING'
             THEN t.amount ELSE 0 END
    ) AS dynamic_spending,

    SUM(
        CASE WHEN t.transaction_type IN ('STATIC_SPENDING','DYNAMIC_SPENDING')
             THEN t.amount ELSE 0 END
    ) AS total_spending,

    SUM(
        CASE
            WHEN t.transaction_type IN ('MAIN_INCOME','ADDITIONAL_INCOME')
                THEN t.amount
            WHEN t.transaction_type IN ('STATIC_SPENDING','DYNAMIC_SPENDING')
                THEN -t.amount
            ELSE 0
        END
    ) AS remaining_money

FROM transactions t
WHERE t.status = 'POSTED'
  AND t.deleted_at IS NULL
GROUP BY
    t.user_id,
    YEAR(t.transaction_date),
    MONTH(t.transaction_date),
    t.currency_code;

