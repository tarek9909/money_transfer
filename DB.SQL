-- 21. Safe-delete rules
-- =====================================================================

-- Accounts and wallets:
--   Prefer archive by setting is_active = 0 and archived_at = NOW().
--
-- Transactions:
--   Prefer:
--      status = 'VOIDED',
--      deleted_at = NOW()
--
-- rather than a hard DELETE.
--
-- Transfers:
--   Prefer:
--      status = 'VOIDED',
--      deleted_at = NOW()
--
-- Static templates:
--   Prefer archive; never rewrite historical paid transaction amounts.
--
-- This keeps old monthly reports reproducible.

