-- =====================================================================
-- Personal Money Tracker
-- Complete MySQL Database Schema
-- Target: MySQL 5.7+ / MySQL 8.x
-- Stack: Flutter + Node.js/Express + MySQL
--
-- Scope:
--   - Main income
--   - Additional income
--   - Static spending
--   - Dynamic spending
--   - Monthly allowance
--   - Daily allowance support
--   - Remaining money
--   - Cash / Whish wallets
--   - Multiple accounts and sub-accounts
--   - Transfers between wallets/accounts
--   - Monthly static expense occurrences
--   - Authentication refresh tokens
--   - Dashboard/balance views
--
-- Design notes:
--   * Money uses DECIMAL, never FLOAT/DOUBLE.
--   * Transfers are separate from income/spending and therefore never
--     affect total income or total spending.
--   * Wallet balances are derived from opening balance + ledger activity.
--   * Transactions use soft deletion to preserve history.
--   * Historical static-expense payments are preserved even if the template
--     is changed later.
--   * UUID-like public IDs are generated by database triggers so mobile/API
--     clients do not need to expose sequential database IDs.
-- =====================================================================

